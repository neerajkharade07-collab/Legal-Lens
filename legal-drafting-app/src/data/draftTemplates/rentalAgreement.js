/** DEMO preliminary structure for a rental agreement. Not an authoritative legal document. */
import { doc, p, pJustify, pCenter, h1, h2, f, b, i, blank, LINE } from './builders';

export function buildRentalAgreement() {
  return doc(
    h1('Rental Agreement'),
    pJustify(
      'This Rental Agreement (the “Agreement”) is made and executed at ',
      LINE,
      ' on ',
      LINE,
      '.',
    ),
    pCenter(b('BETWEEN')),
    pJustify(
      f('landlordName'),
      ', residing at ',
      f('landlordAddress'),
      ' (contact: ',
      f('landlordContact'),
      '), hereinafter referred to as the “Landlord”, of the ONE PART;',
    ),
    pCenter(b('AND')),
    pJustify(
      f('tenantName'),
      ', residing at ',
      f('tenantAddress'),
      ' (contact: ',
      f('tenantContact'),
      '), hereinafter referred to as the “Tenant”, of the OTHER PART.',
    ),
    pJustify('The Landlord and the Tenant are together referred to as the “Parties”.'),
    h2('1. Premises'),
    pJustify(
      'The Landlord agrees to let out the ',
      f('propertyType'),
      ' situated at ',
      f('propertyAddress'),
      ' (the “Premises”) to the Tenant on the terms and conditions set out in this Agreement.',
    ),
    h2('2. Term'),
    pJustify(
      'This Agreement shall be for a period of ',
      f('duration'),
      ' commencing from ',
      f('startDate'),
      ', and may be renewed by mutual written consent of the Parties.',
    ),
    h2('3. Rent'),
    pJustify(
      'The Tenant shall pay a monthly rent of ',
      f('monthlyRent'),
      ', payable on or before ',
      f('paymentDueDate'),
      '.',
    ),
    h2('4. Security deposit'),
    pJustify(
      'The Tenant has paid / shall pay a refundable security deposit of ',
      f('securityDeposit'),
      '. The deposit shall be refunded at the end of the term, subject to deduction of any unpaid dues or the cost of repairing damage beyond normal wear and tear.',
    ),
    h2('5. Lock-in period'),
    pJustify(
      'Neither Party shall terminate this Agreement during the lock-in period of ',
      f('lockInPeriod'),
      ' from the start date, except as mutually agreed in writing.',
    ),
    h2('6. Termination and notice'),
    pJustify(
      'After the lock-in period, either Party may terminate this Agreement by giving ',
      f('noticePeriod'),
      ' prior written notice to the other Party. On termination, the Tenant shall hand over vacant and peaceful possession of the Premises.',
    ),
    h2('7. Maintenance'),
    pJustify(f('maintenanceResponsibility')),
    h2('8. Utilities'),
    pJustify(f('utilityResponsibility')),
    h2('9. Use of premises'),
    pJustify(
      'The Tenant shall use the Premises only for the agreed purpose, shall not sub-let or part with possession without the Landlord’s prior written consent, and shall keep the Premises in good condition.',
    ),
    h2('10. Special conditions'),
    pJustify(f('specialConditions')),
    h2('11. Dispute resolution'),
    pJustify(i('[Dispute resolution terms, if any, to be agreed by the Parties.]')),
    blank(),
    pJustify(
      'IN WITNESS WHEREOF, the Parties have signed this Agreement on the date and at the place first mentioned above.',
    ),
    blank(),
    p(b('LANDLORD'), '  ', LINE),
    p(f('landlordName')),
    blank(),
    p(b('TENANT'), '  ', LINE),
    p(f('tenantName')),
    blank(),
    p(b('WITNESSES')),
    p('1. ', LINE),
    p('2. ', LINE),
  );
}
